@pytest.mark.parametrize(
    "plugin_id",
    ["..", "", ".", "../config", "clock/..", "../../InkyPi", "Clock", "a b", "-rf"],
)
def test_uninstall_refuses_ids_that_are_not_plugin_names(
    fake_install: FakeInstall, plugin_id: str
) -> None:
    before = fake_install.snapshot()

    proc = fake_install.run("uninstall", plugin_id)

    assert proc.returncode != 0
    assert "Invalid plugin id" in proc.stdout
    assert fake_install.snapshot() == before
    assert not [c for c in fake_install.calls() if "restart" in c]


