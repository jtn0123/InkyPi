"""The ``inkypi plugin`` command (install/cli/inkypi-plugin) on a fake install.

E9: the command ran ``rm -rf`` on ``src/plugins/<id>`` with the id unchecked,
so ``uninstall ..`` deleted ``src/`` (device.json and uploads), ``uninstall ""``
deleted every plugin, and ``install clock <url>`` replaced a built-in plugin.
F6: it ran a plain ``pip install -r`` into the app's venv, which could move
packages the app is locked to.

Each test lays out the same tree as a real install: a git checkout holding
``src/`` and ``install/requirements.txt``, and a ``PROJECT_DIR`` (like
``/usr/local/inkypi``) whose ``src`` links into it. ``sudo`` and ``systemctl``
are stubs on ``PATH``; git is real.
"""

from __future__ import annotations

import base64
import hashlib
import os
import shutil
import subprocess
import sys
import zipfile
from dataclasses import dataclass
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
PLUGIN_CLI = REPO_ROOT / "install" / "cli" / "inkypi-plugin"

# A locked package the fake app depends on, with its hash, as `uv export`
# writes the lock.
_LOCK_TEMPLATE = """\
# This file was autogenerated by uv via the following command:
#    uv export --format requirements.txt --no-dev --no-emit-project
lockedpkg==1.0 \\
    --hash=sha256:{digest}
    # via inkypi
linuxonly==2.0 ; sys_platform == 'linux' \\
    --hash=sha256:{digest}
    # via inkypi
"""

_GIT_IDENTITY = {
    "GIT_AUTHOR_NAME": "t",
    "GIT_AUTHOR_EMAIL": "t@example.invalid",
    "GIT_COMMITTER_NAME": "t",
    "GIT_COMMITTER_EMAIL": "t@example.invalid",
    # Keep the developer's own git config (signing, url rewrites,
    # safe.directory) out of these repos.
    "GIT_CONFIG_GLOBAL": os.devnull,
    "GIT_CONFIG_NOSYSTEM": "1",
}


@dataclass
class FakeInstall:
    root: Path
    repo: Path
    project: Path
    venv: Path
    log: Path
    env: dict[str, str]

    @property
    def plugins(self) -> Path:
        return self.repo / "src" / "plugins"

    def run(self, *args: str, **extra_env: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            ["bash", str(PLUGIN_CLI), *args],
            env={**self.env, **extra_env},
            capture_output=True,
            text=True,
            timeout=60,
            check=False,
        )

    def calls(self) -> list[str]:
        if not self.log.exists():
            return []
        return self.log.read_text(encoding="utf-8").splitlines()

    def snapshot(self) -> dict[str, bytes]:
        """Every file under the checkout's src/, by relative path."""
        src = self.repo / "src"
        return {
            str(p.relative_to(src)): p.read_bytes()
            for p in sorted(src.rglob("*"))
            if p.is_file() and not p.is_symlink()
        }


def _git(cwd: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", "-C", str(cwd), *args],
        env={**os.environ, **_GIT_IDENTITY},
        capture_output=True,
        text=True,
        check=True,
    )
    return result.stdout


def _stub(bin_dir: Path, name: str, body: str) -> None:
    path = bin_dir / name
    path.write_text(f"#!/bin/bash\n{body}\n", encoding="utf-8")
    path.chmod(0o755)


@pytest.fixture
def fake_install(tmp_path: Path) -> FakeInstall:
    if not shutil.which("bash") or not shutil.which("git"):
        pytest.skip("bash and git are required")
    repo = tmp_path / "InkyPi"
    plugins = repo / "src" / "plugins"
    for plugin_id in ("clock", "weather"):
        (plugins / plugin_id).mkdir(parents=True)
        (plugins / plugin_id / "plugin-info.json").write_text(
            f'{{"id": "{plugin_id}", "display_name": "{plugin_id}"}}\n'
        )
        (plugins / plugin_id / f"{plugin_id}.py").write_text("# built-in\n")
    (plugins / "base_plugin").mkdir()
    (plugins / "base_plugin" / "base_plugin.py").write_text("# base\n")
    (repo / "install").mkdir()
    (repo / "install" / "requirements.txt").write_text(
        _LOCK_TEMPLATE.format(digest="0" * 64)
    )
    _git(tmp_path, "init", "-q", "-b", "main", str(repo))
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", "app")
    # Runtime files the app writes; untracked, as on a device.
    (repo / "src" / "config").mkdir()
    (repo / "src" / "config" / "device.json").write_text('{"name": "frame"}\n')
    (repo / "src" / "static" / "images" / "saved").mkdir(parents=True)
    (repo / "src" / "static" / "images" / "saved" / "upload.png").write_bytes(b"png")

    project = tmp_path / "usr_local_inkypi"
    project.mkdir()
    (project / "src").symlink_to(repo / "src", target_is_directory=True)
    venv = project / "venv_inkypi"
    (venv / "bin").mkdir(parents=True)

    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    log = tmp_path / "calls.log"
    _stub(bin_dir, "sudo", f'echo "sudo $*" >> "{log}"\n"$@"')
    _stub(bin_dir, "systemctl", f'echo "systemctl $*" >> "{log}"')
    # Records the pip call and keeps the constraints file, which the command
    # deletes on exit. PIP_STUB_RC sets the exit status.
    _stub(
        venv / "bin",
        "python",
        f'echo "python $*" >> "{log}"\n'
        'prev=""\n'
        'for arg in "$@"; do\n'
        f'  [ "$prev" = --constraint ] && cp "$arg" "{tmp_path}/constraints.seen"\n'
        '  prev="$arg"\n'
        "done\n"
        'exit "${PIP_STUB_RC:-0}"',
    )

    env = {
        **os.environ,
        **_GIT_IDENTITY,
        "PATH": f"{bin_dir}:{os.environ['PATH']}",
        "PROJECT_DIR": str(project),
        "VENV_PATH": str(venv),
        "APPNAME": "inkypi",
    }
    return FakeInstall(tmp_path, repo, project, venv, log, env)


def _publish_plugin(root: Path, plugin_id: str, requirements: str | None = None) -> str:
    """A third-party plugin repo laid out as docs/building_plugins.md asks."""
    repo = root / f"InkyPi-{plugin_id}"
    (repo / plugin_id).mkdir(parents=True)
    (repo / plugin_id / "plugin-info.json").write_text(
        f'{{"id": "{plugin_id}", "display_name": "{plugin_id}"}}\n'
    )
    (repo / plugin_id / f"{plugin_id}.py").write_text("# third party\n")
    if requirements is not None:
        (repo / plugin_id / "requirements.txt").write_text(requirements)
    (repo / "README.md").write_text("plugin\n")
    _git(root, "init", "-q", "-b", "main", str(repo))
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", "plugin")
    return repo.as_uri()


def _add_third_party(fake: FakeInstall, plugin_id: str) -> Path:
    """An installed third-party plugin: untracked in the checkout."""
    path = fake.plugins / plugin_id
    path.mkdir()
    (path / "plugin-info.json").write_text(f'{{"id": "{plugin_id}"}}\n')
    return path


