def test_requirements_are_installed_with_the_lock_as_constraints(
    fake_install: FakeInstall,
) -> None:
    url = _publish_plugin(fake_install.root, "weather_plus", "lockedpkg\nextra\n")

    proc = fake_install.run("install", "weather_plus", url)

    assert proc.returncode == 0, proc.stdout + proc.stderr
    req_file = fake_install.project / "src/plugins/weather_plus/requirements.txt"
    pip_calls = [c for c in fake_install.calls() if c.startswith("python ")]
    assert len(pip_calls) == 1
    args = pip_calls[0].split()
    assert args[1:4] == ["-m", "pip", "install"]
    assert args[args.index("-r") + 1] == str(req_file)
    assert "--constraint" in args
    # The lock's pins without its hashes: hashes in a constraints file put pip
    # into --require-hashes mode, which rejects every unpinned plugin package.
    constraints = (fake_install.root / "constraints.seen").read_text()
    assert constraints.splitlines() == [
        "lockedpkg==1.0",
        "linuxonly==2.0 ; sys_platform == 'linux'",
    ]
    assert "not hash-checked" in proc.stdout
    assert "systemctl restart inkypi.service" in fake_install.calls()


def test_a_requirements_conflict_fails_and_removes_the_plugin(
    fake_install: FakeInstall,
) -> None:
    url = _publish_plugin(fake_install.root, "weather_plus", "lockedpkg>=2\n")

    proc = fake_install.run("install", "weather_plus", url, PIP_STUB_RC="1")

    assert proc.returncode != 0
    assert "could not be installed alongside InkyPi's locked packages" in proc.stdout
    assert "No locked package was changed" in proc.stdout
    assert not (fake_install.plugins / "weather_plus").exists()
    assert not [c for c in fake_install.calls() if "restart" in c]


def test_a_missing_lock_file_stops_the_install(fake_install: FakeInstall) -> None:
    url = _publish_plugin(fake_install.root, "weather_plus", "extra\n")
    (fake_install.repo / "install" / "requirements.txt").unlink()

    proc = fake_install.run("install", "weather_plus", url)

    assert proc.returncode != 0
    assert "lock file was not found" in proc.stdout
    assert not [c for c in fake_install.calls() if c.startswith("python ")]
    assert not (fake_install.plugins / "weather_plus").exists()


def _wheel(directory: Path, name: str, version: str, *requires: str) -> None:
    """A minimal pure-Python wheel, so real pip can run with no index."""
    dist = f"{name}-{version}.dist-info"
    files = {
        f"{name}/__init__.py": b"",
        f"{dist}/METADATA": (
            f"Metadata-Version: 2.1\nName: {name}\nVersion: {version}\n"
            + "".join(f"Requires-Dist: {r}\n" for r in requires)
        ).encode(),
        f"{dist}/WHEEL": (
            b"Wheel-Version: 1.0\nGenerator: test\nRoot-Is-Purelib: true\n"
            b"Tag: py3-none-any\n"
        ),
    }
    record = []
    for path, data in files.items():
        digest = base64.urlsafe_b64encode(hashlib.sha256(data).digest()).rstrip(b"=")
        record.append(f"{path},sha256={digest.decode()},{len(data)}")
    record.append(f"{dist}/RECORD,,")
    files[f"{dist}/RECORD"] = ("\n".join(record) + "\n").encode()
    with zipfile.ZipFile(directory / f"{name}-{version}-py3-none-any.whl", "w") as z:
        for path, data in files.items():
            z.writestr(path, data)


@pytest.mark.parametrize(
    ("plugin_requires", "installs"),
    [("lockedpkg", "lockedpkg-1.0"), ("lockedpkg>=2", None)],
    ids=["compatible", "conflict"],
)
def test_real_pip_keeps_locked_packages_on_their_locked_version(
    fake_install: FakeInstall,
    plugin_requires: str,
    installs: str | None,
) -> None:
    """Real pip, offline. lockedpkg 2.0 is on offer, but the lock says 1.0.

    A plugin that accepts 1.0 gets 1.0; one that needs 2.0 is refused rather
    than moving the app's package.
    """
    wheels = fake_install.root / "wheels"
    wheels.mkdir()
    _wheel(wheels, "lockedpkg", "1.0")
    _wheel(wheels, "lockedpkg", "2.0")
    _wheel(wheels, "plugdep", "1.0", plugin_requires)
    lock = fake_install.repo / "install" / "requirements.txt"
    digest = hashlib.sha256((wheels / "lockedpkg-1.0-py3-none-any.whl").read_bytes())
    lock.write_text(_LOCK_TEMPLATE.format(digest=digest.hexdigest()))
    (fake_install.venv / "bin" / "python").write_text(
        f'#!/bin/bash\nexec "{sys.executable}" "$@"\n'
    )
    target = fake_install.root / "site-packages"
    url = _publish_plugin(fake_install.root, "weather_plus", "plugdep\n")

    proc = fake_install.run(
        "install",
        "weather_plus",
        url,
        PIP_NO_INDEX="1",
        PIP_FIND_LINKS=str(wheels),
        PIP_TARGET=str(target),
        PIP_CONFIG_FILE=os.devnull,
        PIP_DISABLE_PIP_VERSION_CHECK="1",
        PIP_NO_INPUT="1",
    )

    output = proc.stdout + proc.stderr
    if installs is None:
        assert proc.returncode != 0, output
        assert "ResolutionImpossible" in output
        assert not (fake_install.plugins / "weather_plus").exists()
    else:
        assert proc.returncode == 0, output
        assert (target / f"{installs}.dist-info").is_dir()
        assert not (target / "lockedpkg-2.0.dist-info").exists()
