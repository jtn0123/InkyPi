"""scripts/export_requirements.sh and the Dependabot workflow that runs it."""

from __future__ import annotations

import os
import shutil
import subprocess
from pathlib import Path
from typing import Any

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[2]
SCRIPT = ROOT / "scripts" / "export_requirements.sh"
WORKFLOW = ROOT / ".github" / "workflows" / "dependabot-exports.yml"
EXPORTS = {
    "install/requirements.txt": "--no-dev",
    "install/requirements-dev.txt": "--group dev",
}

# Stands in for `uv export`: logs its arguments and writes a file with uv's
# header layout, naming the output path it was given and the --frozen flag.
FAKE_UV = """#!/bin/sh
printf '%s\\n' "$*" >> "$UV_LOG"
out=""
prev=""
for arg in "$@"; do
    if [ "$prev" = "--output-file" ]; then out="$arg"; fi
    prev="$arg"
done
{
    echo "# This file was autogenerated by uv via the following command:"
    echo "#    uv $*"
    echo "pkg==1.0 \\\\"
    echo "    --hash=sha256:abc"
} > "$out"
"""


@pytest.fixture
def repo(tmp_path: Path) -> Path:
    """A copy of the script in an empty repo, with the fake uv on PATH."""
    (tmp_path / "scripts").mkdir()
    (tmp_path / "install").mkdir()
    shutil.copy(SCRIPT, tmp_path / "scripts" / SCRIPT.name)
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    uv = bin_dir / "uv"
    uv.write_text(FAKE_UV)
    uv.chmod(0o755)
    return tmp_path


def _run(repo: Path, *args: str) -> subprocess.CompletedProcess[str]:
    env = os.environ.copy()
    env["PATH"] = f"{repo / 'bin'}{os.pathsep}{env['PATH']}"
    env["UV_LOG"] = str(repo / "uv.log")
    return subprocess.run(
        ["bash", str(repo / "scripts" / SCRIPT.name), *args],
        cwd=repo,
        env=env,
        capture_output=True,
        text=True,
        timeout=60,
        check=False,
    )


def test_exports_both_files_from_the_frozen_lock(repo: Path) -> None:
    result = _run(repo)
    assert result.returncode == 0, result.stderr

    calls = (repo / "uv.log").read_text().splitlines()
    assert calls == [
        f"export --frozen --format requirements.txt {selection} --no-emit-project "
        f"--output-file {path} --quiet"
        for path, selection in EXPORTS.items()
    ]


def test_header_names_the_committed_file_as_the_real_exports_do(
    repo: Path,
) -> None:
    out = repo / "elsewhere"
    out.mkdir()
    runtime, dev = out / "runtime.txt", out / "dev.txt"
    assert _run(repo, str(runtime), str(dev)).returncode == 0

    for written, committed in zip((runtime, dev), EXPORTS, strict=True):
        lines = written.read_text().splitlines()
        real = (ROOT / committed).read_text().splitlines()
        # Same header as the committed export, whatever path uv wrote to and
        # without --frozen, so the drift check diffs only the requirements.
        assert lines[:2] == real[:2]
        assert lines[2:] == ["pkg==1.0 \\", "    --hash=sha256:abc"]
    assert not list((repo / "install").iterdir())
    assert sorted(p.name for p in out.iterdir()) == ["dev.txt", "runtime.txt"]


def test_fails_when_uv_fails(repo: Path) -> None:
    (repo / "bin" / "uv").write_text("#!/bin/sh\nexit 2\n")
    result = _run(repo)
    assert result.returncode != 0
    assert not list((repo / "install").iterdir())


def test_drift_check_compares_against_the_same_export() -> None:
    drift = (ROOT / "scripts" / "check_requirements_drift.sh").read_text()
    assert 'bash scripts/export_requirements.sh "${tmp_export}" "${tmp_dev}"' in drift
    code = [line for line in drift.splitlines() if not line.lstrip().startswith("#")]
