def _workflow() -> dict[str, Any]:
    loaded = yaml.safe_load(WORKFLOW.read_text())
    assert isinstance(loaded, dict)
    # PyYAML reads the `on` key as the boolean True.
    return {str(key): value for key, value in loaded.items()}


def _run_steps(job: dict[str, Any]) -> list[str]:
    return [str(step["run"]) for step in job["steps"] if "run" in step]


def test_runs_only_for_dependabot_lock_changes() -> None:
    workflow = _workflow()
    assert workflow["True"] == {"pull_request": {"paths": ["uv.lock"]}}
    condition = workflow["jobs"]["export"]["if"]
    for check in (
        "github.actor == 'dependabot[bot]'",
        "github.event.pull_request.user.login == 'dependabot[bot]'",
        "github.event.pull_request.head.repo.full_name == github.repository",
    ):
        assert check in condition
    # The push job only runs after a successful export.
    assert workflow["jobs"]["push"]["needs"] == "export"


def test_the_job_that_runs_uv_cannot_write() -> None:
    workflow = _workflow()
    assert workflow["permissions"] == {}
    export = workflow["jobs"]["export"]
    assert export["permissions"] == {"contents": "read"}
    checkout = export["steps"][0]
    assert checkout["uses"].startswith("actions/checkout@")
    assert checkout["with"]["persist-credentials"] is False
    assert "bash scripts/export_requirements.sh" in _run_steps(export)
    assert any("--require-hashes" in run for run in _run_steps(export))


def test_the_job_that_pushes_runs_nothing_from_the_branch() -> None:
    push = _workflow()["jobs"]["push"]
    assert push["permissions"] == {"contents": "write"}
    (script,) = _run_steps(push)
    for forbidden in ("scripts/", "bash ", "python", "uv ", "make ", "--force", " -f "):
        assert forbidden not in script, forbidden
    # Dependabot keeps rebasing over a commit marked this way; CI must still
    # run on it, so nothing in the message may skip workflows.
    assert "[dependabot skip]" in script
    assert "skip ci" not in script.lower() and "ci skip" not in script.lower()
    assert 'git push origin "HEAD:refs/heads/$HEAD_REF"' in script
